bool TMC_Compare(uint8_t *soure,uint8_t *dest,uint32_t length)
{
	uint32_t i;
	for(i=0;i<length;i++)
	{
		if(soure[i]!=dest[i])
		{
			return FALSE;
		}
	}
	return TRUE;
}


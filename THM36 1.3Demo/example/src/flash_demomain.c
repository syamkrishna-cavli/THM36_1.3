	{
		return ;
	}
	
	memcpy(testbuf, (uint8_t *)Test_Address, 200);

	/*Double words write,without stricter read,no verify*/
	Program.HardVerify = FLASH_PROGRAM_NOT_VERIFY;
	Program.ProgramVread = FLASH_PROGRAM_NOT_VREAD;
	status = TMC_FLASH_ProgramDoubleWord(Test_Address,(uint32_t)Flash_Buf,64,&Program,0x10000000);
	if (status != TMC_OK)
	{
		return ;
	}
   
    
	/*Reset DCache after flash data is changed.*/
	Flash_DcacheCmd(Flash_ACC,DISABLE);
	while(Flash_CacheGetStatus(Flash_ACC,FLASH_CACHE_Flag_DCACHE) == BUSY);
	Flash_DcacheRest(Flash_ACC,ENABLE);
	Flash_DcacheRest(Flash_ACC,DISABLE);
	Flash_DcacheCmd(Flash_ACC,ENABLE);
	

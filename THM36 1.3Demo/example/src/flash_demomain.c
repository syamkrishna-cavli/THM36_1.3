void ReturnBL_Test(void)
{
	uint32_t flashaddr;
	Flash_EraseTypeDef EraseMode;
	Flash_ProgramTypeDef Program;
	__disable_irq();

	flashaddr = FLASH_ADDR_START2;
	TMC_FLASH_Msp_Init();
	EraseMode.HardVerify = FLASH_ERASE_NOT_VERIFY;	
	TMC_FLASH_ErasePage(flashaddr,1,&EraseMode,0x10000000);

	Program.HardVerify = FLASH_PROGRAM_NOT_VERIFY;
	Program.ProgramVread = FLASH_PROGRAM_NOT_VREAD;
	TMC_FLASH_ProgramHalfPage(flashaddr,(uint32_t)BL_Firstpage, 32, &Program, 0x10000000);
	TMC_FLASH_ProgramHalfPage(flashaddr+256,(uint32_t)(BL_Firstpage+256),32,&Program,0x10000000);

	if(TMC_Compare((uint8_t*)flashaddr, (uint8_t*)BL_Firstpage, 0x200)== FALSE)
	{
		return;
	}
}

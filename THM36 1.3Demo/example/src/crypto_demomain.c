/**
    * @brief RSA_Demo_Test:
                1.Generate key pair
                2.Save CRT parameters
                3.Encryption
                4.Decryption
                5.Decryption-CRT
    * @param  None
    * @retval None
 */
void RSA_Demo_Test(void)
{
	BigNum_t inputBuf, outputBuf;

	RSAPrivKey_t RSA_PrivKey;
	RSAPubKey_t RSA_PubKey;
	RSAPrivKeyCrt_t RSA_PrivKeyCrt;
	RSAKeyGenOut_t rsaGenOut;
	//RSAKGOut_t rsaGenOut;
	unsigned short sCryptResult = PKE_ALG_OK;
	unsigned char result = 0x00;
	unsigned char bGenKeyMode = 0x00;

	/* GenerateKeyPair */
	RSA_PubKey.E.p = RSA_KEY_E;
	RSA_PubKey.E.length = RSA_KEY_E_LEN;
	bGenKeyMode = RSA_GEN_KEY_MODE_MSB_BIT_1 |
				  RSA_GEN_KEY_MODE_VERIFY;//Verify the Key,the most significant bit must be 1.
	sCryptResult = tmcRSAKeyPairGen(&rsaGenOut, &RSA_PubKey.E, RSA_KEY_BIT_LEN, bGenKeyMode);
	if(PKE_ALG_OK != sCryptResult)
	{
		result = 0x1;
		goto END;
	}
	else
	{
		//save Key.
		memcpy(RSA_KEY_N, rsaGenOut.PriKey.N.p, RSA_KEY_LEN);
		memcpy(RSA_KEY_D, rsaGenOut.PriKey.D.p, RSA_KEY_LEN);
		memcpy(RSA_CRT_KEY_P, rsaGenOut.PriCrtKey.P.p, RSA_CRT_KEY_LEN);
		memcpy(RSA_CRT_KEY_Q, rsaGenOut.PriCrtKey.Q.p, RSA_CRT_KEY_LEN);
		memcpy(RSA_CRT_KEY_DP, rsaGenOut.PriCrtKey.DP.p, RSA_CRT_KEY_LEN);
		memcpy(RSA_CRT_KEY_DQ, rsaGenOut.PriCrtKey.DQ.p, RSA_CRT_KEY_LEN);
		memcpy(RSA_CRT_KEY_QINV, rsaGenOut.PriCrtKey.QInv.p, RSA_CRT_KEY_LEN);
	}

	/* RSA-Encrypt */
	RSA_PubKey.N.p = RSA_KEY_N;
	RSA_PubKey.N.length = RSA_KEY_LEN;

	inputBuf.p = RSAPlainData;
	inputBuf.length = RSA_PLAIN_DATA_LEN;
	outputBuf.p = RSAEncData;
	sCryptResult = tmcRSAEncrypt(&outputBuf, &inputBuf, &RSA_PubKey);
	if(PKE_ALG_OK != sCryptResult)
	{
		result = 2;
		goto END;
	}

	/* RSA-Decrypt */
	RSA_PrivKey.N.p = RSA_KEY_N;
	RSA_PrivKey.N.length = RSA_KEY_LEN;

	RSA_PrivKey.D.p = RSA_KEY_D;
	RSA_PrivKey.D.length = RSA_KEY_LEN;
	inputBuf.p = RSAEncData;
	inputBuf.length = RSA_KEY_LEN;
	outputBuf.p = gCryptoResultBuff;
	sCryptResult = tmcRSADecrypt(&outputBuf, &inputBuf, &RSA_PrivKey);
	if(PKE_ALG_OK != sCryptResult)
	{
		result = 3;
		goto END;
	}
	//check decrypt result
	if (RSA_PLAIN_DATA_LEN < RSA_KEY_LEN)
	{
		//If the length of plain data less than the length of Key,padding zero in front.
		if (FALSE == TMC_Compare(gCryptoResultBuff + (RSA_KEY_LEN - RSA_PLAIN_DATA_LEN), RSAPlainData,
								 RSA_PLAIN_DATA_LEN))
		{
			result = 4;
			goto END;
		}
	}
	else
	{
		if (FALSE == TMC_Compare(gCryptoResultBuff, RSAPlainData, RSA_PLAIN_DATA_LEN))
		{
			result = 5;
			goto END;
		}
	}

	/* RSA-CRT Decypt */
	RSA_PrivKeyCrt.P.p = RSA_CRT_KEY_P;
	RSA_PrivKeyCrt.P.length = RSA_CRT_KEY_LEN;
	RSA_PrivKeyCrt.Q.p = RSA_CRT_KEY_Q;
	RSA_PrivKeyCrt.Q.length = RSA_CRT_KEY_LEN;
	RSA_PrivKeyCrt.DP.p = RSA_CRT_KEY_DP;
	RSA_PrivKeyCrt.DP.length = RSA_CRT_KEY_LEN;
	RSA_PrivKeyCrt.DQ.p = RSA_CRT_KEY_DQ;
	RSA_PrivKeyCrt.DQ.length = RSA_CRT_KEY_LEN;
	RSA_PrivKeyCrt.QInv.p = RSA_CRT_KEY_QINV;
	RSA_PrivKeyCrt.QInv.length = RSA_CRT_KEY_LEN;
	inputBuf.p = RSAEncData;
	inputBuf.length = RSA_KEY_LEN;
	outputBuf.p = gCryptoResultBuff;
	sCryptResult = tmcRSADecryptCrt_SU(&outputBuf, &inputBuf, &RSA_PrivKeyCrt, &(RSA_PubKey.E));
	if(PKE_ALG_OK != sCryptResult)
	{
		result = 6;
		goto END;
	}
	//check decrypt result
	if (RSA_PLAIN_DATA_LEN < RSA_KEY_LEN)
	{
		//If the length of plain data less than the length of Key,padding zero in front.
		if (FALSE == TMC_Compare(gCryptoResultBuff + (RSA_KEY_LEN - RSA_PLAIN_DATA_LEN), RSAPlainData,
								 RSA_PLAIN_DATA_LEN))
		{
			result = 7;
		}
	}
	else
	{
		if (FALSE == TMC_Compare(gCryptoResultBuff, RSAPlainData, RSA_PLAIN_DATA_LEN))
		{
			result = 8;
		}
	}
END:
	if (result != 0x0)
	{
		while(1);
	}
}


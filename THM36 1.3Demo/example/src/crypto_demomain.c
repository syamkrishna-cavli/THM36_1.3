/**
    * @brief ECC_Demo_Test:
                1.Check whether the curve parameters are valid
                2.Generate key pair
                3.ECC sign
                4.ECC verify
    * @param  None
    * @retval None
 */
void ECC_Demo_Test(void)
{
    BigNum_t inputBuf, outputBuf, PlainTemp, CipherTemp;
    unsigned short sCryptResult = PKE_ALG_OK;
    unsigned char result = 0x00, pucMask[8] = {0};
    
    /* Check ECC Parameter */
    sCryptResult = tmcECCParamCheck(&ECC_DOMAIN1);
    if (PKE_ALG_OK != sCryptResult)
    {
        result = 0x01;
        goto END;
    }
    
    /* ECC GenerateKeyPair */
    sCryptResult = tmcECCKeyGen(&ECC_P1ubKey1, &ECC_P1rivKey1, &ECC_DOMAIN1, ECC_GEN_KEY_MODE_GEN_PRI_KEY);
    if (PKE_ALG_OK != sCryptResult)
    {
        result = 0x02;
        goto END;
    }
    
    /* ECC Sign */
    inputBuf.p = ECCPlainData;
    inputBuf.length = ECC_P1LAIN_DATA_LEN;
    outputBuf.p = ECCEncData;
    outputBuf.length = 0x40;
    sCryptResult = tmcECCSign(&outputBuf, &inputBuf, &ECC_P1rivKey1, &ECC_DOMAIN1) ;
    if (PKE_ALG_OK != sCryptResult)
    {
        result = 0x03;
        goto END;
    }
    
    /* ECC Verify */
    sCryptResult = tmcECCVerify(&inputBuf, &ECC_P1ubKey1, &outputBuf, &ECC_DOMAIN1);
    if (PKE_ALG_OK != sCryptResult)
    {
        result = 0x04;
        goto END;
    }
    
    /* ECC Check point is on the curve */
    /* The public key is on the curve */
    sCryptResult = tmcECCPtChk(&ECC_P1ubKey1, &ECC_DOMAIN1);
    if (PKE_ALG_OK != sCryptResult)
    {
        result = 0x05;
        goto END;
    }
    
    /* The plain is not on the curve */
    sCryptResult = tmcECCPtChk(&Plain_BigNum, &ECC_DOMAIN1);
    
    memcpy(ECC_P1RIV_KEY, EccPrivKey,0x20);
    memcpy(ECC_P1UB_KEY, EccPubKey,0x40);
    /* ECC Encrypt */
    CipherTemp.p = CipherBuf;
    sCryptResult = tmcECCEncrypt(&CipherTemp, &Plain_BigNum, &ECC_P1ubKey1, &Share1, &Share2, &ECC_DOMAIN1, 0);
    if (PKE_ALG_OK != sCryptResult)
    {
        result = 0x06;
        goto END;
    }
    
    /* ECC Decrypt */
    PlainTemp.p = PlainBuf; 
    sCryptResult = tmcECCDecrypt(&PlainTemp, &CipherTemp, &ECC_P1rivKey1, &Share1, &Share2, pucMask, &ECC_DOMAIN1, 0);
    if (PKE_ALG_OK != sCryptResult)
    {
        result = 0x07;
        goto END;
    }
    /* Check data calculation is correct */
    if (memcmp(PlainBuf, Plain, 64))
    {
        result = 0x08;
        goto END;
    }
    
    memset(PlainBuf, 0, 64);
    
    PlainTemp.p = PlainBuf;
    sCryptResult = tmcECCDecrypt(&PlainTemp, &Cipher_BigNum, &ECC_P1rivKey1, &Share1, &Share1, pucMask, &ECC_DOMAIN1, 0);
    if (PKE_ALG_OK != sCryptResult)
    {
        result = 0x07;
        goto END;
    }
    /* Check data calculation is correct */
    if (memcmp(PlainBuf, Plain, 64))
    {
        result = 0x08;
        goto END;
    }

END:
	if (result != 0x0)
	{
		while(1);
	}
}


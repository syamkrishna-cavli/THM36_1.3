/**
    * @brief AES_CFB_Demo_Test:
                1.Encryption in 128-bit CFB mode
                2.Decryption in 128-bit CFB mode
                3.Encryption in 192-bit CFB mode
                4.Decryption in 192-bit CFB mode
                5.Encryption in 256-bit CFB mode
                6.Decryption in 256-bit CFB mode
    * @param  None
    * @retval None
 */
void AES_CFB_Demo_Test(void)
{
	uint16_t resAES;
	uint8_t randomLen;
	do{
		tmcGetRandomNum(&randomLen, 1);		//	1 byte random length, <256
	}while(randomLen == 0);		//	must  >0

	// memset(gPlainDataBuff, 0x00, randomLen);
	UART_printf("AES test len = %d\r\n", randomLen);
	UART_printf("The plaintext is:\r\n");
	for(uint32_t i=0; i < randomLen; i++)
	{
		gPlainDataBuff[i] = i;		// 0x00 ~ randomLen-1
		UART_printf("%02X ", gPlainDataBuff[i]);
	}
	UART_printf("\r\n");
	//AES128
	resAES = AES_CFB(AES128bKey, AES_IV, gPlainDataBuff, gCryptoResultBuff, randomLen, AES_MODE_128_KEY_ENCRYPT);
	if(memcmp(AES128_0_ENCRYPT,  gCryptoResultBuff, randomLen))		//	AES128 CFB encrypt failed
	{
		UART_printf("AES128_0_ENCRYPT ERROR[%04X]\r\n", resAES);
		return;
	}
	UART_printf("AES128_0_ENCRYPT OK[%04X]\r\n", resAES);
	
	resAES = AES_CFB(AES128bKey, AES_IV, AES128_0_ENCRYPT, gCryptoResultBuff, randomLen, AES_MODE_128_KEY_DECRYPT);
	if(memcmp(gPlainDataBuff,  gCryptoResultBuff, randomLen))		//	AES128 CFB decrypt failed
	{
		UART_printf("AES128_0_DECRYPT ERROR[%04X]\r\n", resAES);
		return;
	}
	UART_printf("AES128_0_DECRYPT OK[%04X]\r\n", resAES);

	//AES192
	resAES = AES_CFB(AES192bKey, AES_IV, gPlainDataBuff, gCryptoResultBuff, randomLen, AES_MODE_192_KEY_ENCRYPT);
	if(memcmp(AES192_0_ENCRYPT,  gCryptoResultBuff, randomLen))		//	AES192 CFB encrypt failed
	{
		UART_printf("AES192_0_ENCRYPT ERROR[%04X]\r\n", resAES);
		return;
	}
	UART_printf("AES192_0_ENCRYPT OK[%04X]\r\n", resAES);
	
	resAES = AES_CFB(AES192bKey, AES_IV, AES192_0_ENCRYPT, gCryptoResultBuff, randomLen, AES_MODE_192_KEY_DECRYPT);
	if(memcmp(gPlainDataBuff,  gCryptoResultBuff, randomLen))		//	AES192 CFB decrypt failed
	{
		UART_printf("AES192_0_DECRYPT ERROR[%04X]\r\n", resAES);
		return;
	}
	UART_printf("AES192_0_DECRYPT OK[%04X]\r\n", resAES);

	//AES256
	resAES = AES_CFB(AES256bKey, AES_IV, gPlainDataBuff, gCryptoResultBuff, randomLen, AES_MODE_256_KEY_ENCRYPT);
	if(memcmp(AES256_0_ENCRYPT,  gCryptoResultBuff, randomLen))		//	AES256 CFB encrypt failed
	{
		UART_printf("AES256_0_ENCRYPT ERROR[%04X]\r\n", resAES);
		return;
	}
	UART_printf("AES256_0_ENCRYPT OK[%04X]\r\n", resAES);
	
	resAES = AES_CFB(AES256bKey, AES_IV, AES256_0_ENCRYPT, gCryptoResultBuff, randomLen, AES_MODE_256_KEY_DECRYPT);
	if(memcmp(gPlainDataBuff,  gCryptoResultBuff, randomLen))		//	AES256 CFB decrypt failed
	{
		UART_printf("AES256_0_DECRYPT ERROR[%04X]\r\n", resAES);
		return;
	}
	UART_printf("AES256_0_DECRYPT OK[%04X]\r\n", resAES);
	
	TMC_Delay(3000);
}

